"""Shared bootstrap for the tie-break revalidation sweep (v2).

This package owns two things the repo's original research scripts do not:

1. **A redirected result cache.** `research/control_diagnostic.py` caches to
   `research/_control_diag/`, which currently holds results stamped with the *old*
   engine `d93815344bd3`. Re-running there would either (a) silently reuse the old
   numbers because `run_many` skips on a cache hit, or (b) overwrite the v1 evidence
   that the diff table is measured against. Both are unacceptable, so the cache path is
   rebound to `research/revalidate_v2/_cache/` before anything runs.

2. **A provenance gate.** Every entry point refuses to run unless
   `nsealgo.provenance.provenance()` matches `EXPECTED`. A revalidation that silently
   ran against a different engine, loader, cost model or data panel would produce a
   diff table full of numbers that are not attributable to the tie-break fix, which is
   the one thing these reports must not do.

Nothing in `src/`, `tests/` or the existing reports is imported for side effects; the
harness is imported read-only and only its `run_*` / `make_*` / statistics helpers are
used. Report writing is deliberately NOT reused — each v2 report is generated by its
own module so the prose cannot drift back to the v1 wording.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "src"))
sys.path.insert(0, str(REPO / "research"))

from nsealgo.provenance import provenance  # noqa: E402

#: The fingerprints this revalidation is *for*. Checked before any work is done.
EXPECTED: dict[str, str] = {
    "engine": "29764f562cd5",
    "loader": "c1badf5f7df8",
    "costs": "ba350aef75b3",
    "panel": "389b082b832f",
}

CACHE = Path(__file__).resolve().parent / "_cache"
REPORTS = REPO / "reports"
V1_DIAG = REPO / "reports" / "CONTROL_DIAGNOSTIC.md"
V1_STRESS = REPO / "reports" / "STRESS_v3.md"


class ProvenanceMismatch(RuntimeError):
    """The working tree is not the tree these reports are about."""


def check_provenance(verbose: bool = True) -> dict[str, str]:
    """Assert the working tree fingerprints `EXPECTED`, or raise.

    Returns the provenance dict so callers can stamp it into their own output.
    """
    got = provenance()
    if got != EXPECTED:
        diff = {
            k: (EXPECTED.get(k), got.get(k))
            for k in sorted(set(EXPECTED) | set(got))
            if EXPECTED.get(k) != got.get(k)
        }
        raise ProvenanceMismatch(
            "provenance does not match the tree this revalidation is about; "
            "stopping.\n  component: expected -> actual\n"
            + "\n".join(f"    {k:>7}: {e} -> {a}" for k, (e, a) in diff.items())
        )
    if verbose:
        print("provenance OK      : " + "  ".join(f"{k}={v}" for k, v in sorted(got.items())))
    return got


def stamp(payload: dict) -> dict:
    """Attach provenance to a result payload."""
    payload["provenance"] = provenance()
    return payload


def write_json(name: str, payload: dict) -> Path:
    CACHE.mkdir(parents=True, exist_ok=True)
    p = CACHE / f"{name}.json"
    p.write_text(json.dumps(payload, indent=2, default=str))
    return p


def read_json(name: str) -> dict | None:
    p = CACHE / f"{name}.json"
    return json.loads(p.read_text()) if p.exists() else None


def pctile(x: float) -> str:
    """Format a 0-1 percentile as an English ordinal ("29th", "93rd", "100th")."""
    n = int(round(x * 100))
    if 10 <= n % 100 <= 20:
        suf = "th"
    else:
        suf = {1: "st", 2: "nd", 3: "rd"}.get(n % 10, "th")
    return f"{n}{suf}"


def pp(x: float | None, d: int = 2, sign: bool = True) -> str:
    """Percentage-points, or a percentage when the caller divides first."""
    if x is None:
        return "n/a"
    return f"{x:+.{d}f}" if sign else f"{x:.{d}f}"
